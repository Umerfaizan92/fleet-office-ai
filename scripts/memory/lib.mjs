export function findRoot(from = process.cwd()) {
  const r = spawnSync('git', ['rev-parse', '--show-toplevel'], { cwd: from, encoding: 'utf8' });
  if (r.status === 0) return r.stdout.trim();
  let dir = path.resolve(from);
  while (dir !== path.dirname(dir)) { if (fs.existsSync(path.join(dir, 'CLAUDE.md'))) return dir; dir = path.dirname(dir); }
  return path.resolve(from);
}

export const memDir = (root) => path.join(root, '.claude', 'project-memory');
export const read = (file) => { try { return fs.readFileSync(file, 'utf8'); } catch { return ''; } };

export function git(root, args, { env, input } = {}) {
  const r = spawnSync('git', args, { cwd: root, encoding: 'utf8', input, env: env ? { ...process.env, ...env } : process.env, maxBuffer: 64 * 1024 * 1024 });
  return { ok: r.status === 0, out: (r.stdout || '').replace(/\s+$/, ''), err: (r.stderr || '').trim() };
}

/** Current git state, read-only and without network access (remote refs may be stale). */
export function gitState(root) {
  if (!git(root, ['rev-parse', '--is-inside-work-tree']).ok) return { repo: false };
  const branch = git(root, ['rev-parse', '--abbrev-ref', 'HEAD']).out;
  const head = git(root, ['rev-parse', '--short', 'HEAD']).out;
  const subject = git(root, ['log', '-1', '--format=%s']).out;
  const porcelain = git(root, ['status', '--porcelain=v1', '--untracked-files=all']).out;
  const lines = porcelain ? porcelain.split('\n') : [];
  const untracked = lines.filter((l) => l.startsWith('??')).map((l) => l.slice(3));
  const changed = lines.filter((l) => !l.startsWith('??')).map((l) => l.slice(3));
  const upstreamRef = git(root, ['rev-parse', '--abbrev-ref', '--symbolic-full-name', '@{u}']);
  const remoteBranch = upstreamRef.ok ? upstreamRef.out : (git(root, ['rev-parse', '--verify', '-q', `origin/${branch}`]).ok ? `origin/${branch}` : null);
  const counts = (a, b) => { const r = git(root, ['rev-list', '--left-right', '--count', `${a}...${b}`]); return r.ok ? r.out.split(/\s+/).map(Number) : null; };
  const vsRemote = remoteBranch ? counts('HEAD', remoteBranch) : null;
  const hasMain = git(root, ['rev-parse', '--verify', '-q', 'origin/main']).ok;
  const vsMain = hasMain ? counts('HEAD', 'origin/main') : null;
  const gitDir = git(root, ['rev-parse', '--git-dir']).out;
  const abs = path.isAbsolute(gitDir) ? gitDir : path.join(root, gitDir);
  const operations = [['MERGE_HEAD', 'merge'], ['rebase-merge', 'rebase'], ['rebase-apply', 'rebase or am'], ['CHERRY_PICK_HEAD', 'cherry-pick'], ['REVERT_HEAD', 'revert'], ['BISECT_LOG', 'bisect']]
    .filter(([f]) => fs.existsSync(path.join(abs, f))).map(([, n]) => n);
  const snapshots = recoverySnapshots(root);
  return { repo: true, branch, head, subject, changed, untracked, remoteBranch, ahead: vsRemote?.[0] ?? null, behind: vsRemote?.[1] ?? null, aheadOfMain: vsMain?.[0] ?? null, mainNewer: vsMain?.[1] ?? null, operations, snapshots };
}

export function recoverySnapshots(root) {
  const r = git(root, ['for-each-ref', '--sort=-creatordate', '--format=%(refname)|%(objectname:short)|%(creatordate:iso-strict)|%(subject)', 'refs/recovery/']);
  if (!r.ok || !r.out) return [];
  return r.out.split('\n').map((l) => { const [ref, sha, date, subject] = l.split('|'); return { ref, sha, date, subject }; });
}

export function commitExists(root, rev) { return !!rev && git(root, ['cat-file', '-e', `${rev}^{commit}`]).ok; }
export function isAncestor(root, a, b) { return git(root, ['merge-base', '--is-ancestor', a, b]).ok; }

/** Reads "KEY: value" lines from the generated handover block. */
export function parseHandover(text) {
  const s = text.indexOf(START), e = text.indexOf(END);
  const block = s >= 0 && e > s ? text.slice(s + START.length, e) : text;
  const out = {};
  for (const line of block.split('\n')) {
    const m = line.match(/^\s*(?:[-*]\s*)?\**([A-Z][A-Z ]+?)\**:\s*(.*)$/);
    if (m && HANDOVER_KEYS.includes(m[1].trim())) out[m[1].trim()] = m[2].trim();
  }
  return out;
}

/** Tasks from PENDING_TASKS.md / COMPLETED_TASKS.md: "## T-123 Title" followed by "- Status: X". */
export function parseTasks(text) {
  const tasks = [];
  let cur = null;
  for (const line of text.split('\n')) {
    const h = line.match(/^##\s+(T-\d{3,})\s+(.*)$/);
    if (h) { cur = { id: h[1], title: h[2].trim(), status: null }; tasks.push(cur); continue; }
    if (/^##\s/.test(line)) { cur = null; continue; }
    const s = cur && line.match(/^\s*-\s*Status:\s*([A-Z_]+)/);
    if (s && !cur.status) cur.status = s[1];
  }
  return tasks;
}

export function lastCheckpoint(text) {
  const parts = text.split(/\n(?=## CP-)/).filter((p) => p.startsWith('## CP-'));
  if (!parts.length) return null;
  const last = parts[parts.length - 1];
  const field = (k) => (last.match(new RegExp(`^- ${k}:\\s*(.*)$`, 'm')) || [])[1] || '';
  return { id: last.match(/^## (CP-\d+)/)[1], heading: last.split('\n')[0].replace(/^##\s*/, ''), task: field('Task'), next: field('Next exact action'), commit: field('Commit'), snapshot: field('Recovery snapshot'), count: parts.length };
}

// Patterns that must never appear in project memory (same spirit as scripts/secret-scan.mjs).
const SECRET_PATTERNS = [
  [/AKIA[0-9A-Z]{16}/, 'AWS access key'], [/\b(sk|rk)_live_[0-9a-zA-Z]{10,}/, 'Stripe live key'], [/\bsk-[A-Za-z0-9_-]{20,}/, 'API secret key'],
  [/-----BEGIN [A-Z ]*PRIVATE KEY-----/, 'private key'], [/\bghp_[A-Za-z0-9]{30,}/, 'GitHub token'], [/\bxox[abp]-[A-Za-z0-9-]{10,}/, 'Slack token'],
  [/\b(password|passwd|secret|api[_-]?key|token)\s*[:=]\s*["']?(?!\[stored separately\])[^\s"'`|]{8,}/i, 'credential assignment'],
  [/whsec_(?!wrong)[A-Za-z0-9]{16,}/, 'webhook secret'], [/\b[A-Z2-7]{32}\b/, 'possible authenticator (TOTP) key']
];
export function findSecrets(text) {
  const hits = [];
  for (const [re, name] of SECRET_PATTERNS) if (re.test(text)) hits.push(name);
  return hits;
}

export const nowIso = () => {
  const d = new Date(), off = -d.getTimezoneOffset(), sign = off >= 0 ? '+' : '-', pad = (n) => String(Math.abs(n)).padStart(2, '0');
  const local = new Date(d.getTime() + off * 60000).toISOString().slice(0, 19);
  return `${local}${sign}${pad(Math.trunc(off / 60))}:${pad(off % 60)}`;
};

export function parseArgs(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith('--')) { out._.push(a); continue; }
    const [k, inline] = a.slice(2).split(/=(.*)/s);
    const v = inline !== undefined ? inline : (argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : true);
    if (out[k] === undefined) out[k] = v; else out[k] = [].concat(out[k], v);
  }
  return out;
}
export const list = (v) => (v === undefined || v === true ? [] : [].concat(v).flatMap((x) => String(x).split(/\s*;\s*/)).filter(Boolean));

export function identityEnv(root) {
  const name = git(root, ['config', 'user.name']).out || os.userInfo().username || 'checkpoint';
  const email = git(root, ['config', 'user.email']).out || 'checkpoint@localhost';
  return { GIT_AUTHOR_NAME: name, GIT_AUTHOR_EMAIL: email, GIT_COMMITTER_NAME: name, GIT_COMMITTER_EMAIL: email };
}
